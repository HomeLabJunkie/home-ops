#!/usr/bin/env python3
"""Generate Homepage's services.yaml and settings.yaml from inventory.yaml.

    python3 scripts/homepage.py

Reads  kubernetes/apps/default/homepage/inventory.yaml
Writes kubernetes/apps/default/homepage/app/config/{services,settings}.yaml

Two tabs: "Outside" (public hostnames, plus the cluster apps that Homepage
discovers from HTTPRoute annotations, group CLUSTER_GROUP) and "LAN" (local
addresses). A service appears in each tab it has a link for. Group names must
be unique across tabs, so Outside groups get an " (outside)" suffix.
Commit the inventory and both generated files together.
"""
import pathlib
import shutil
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / "kubernetes/apps/default/homepage"
ICONS = "https://cdn.jsdelivr.net/gh/homarr-labs/dashboard-icons"
CLUSTER_GROUP = "Talos cluster"  # must match gethomepage.dev/group on HTTPRoutes
HEADER = "# Generated by scripts/homepage.py from inventory.yaml: edit that, not this.\n"


def icon(name):
    if name.startswith("png:"):
        return f"{ICONS}/png/{name[4:]}.png"
    return f"{ICONS}/svg/{name}.svg"


def tile(svc, href, other_label, other):
    desc = svc.get("note", "")
    if other:
        desc = f"{desc} · {other_label}: {other}" if desc else f"{other_label}: {other}"
    d = {"icon": icon(svc["icon"]), "href": href}
    if svc.get("monitor", True):
        d["siteMonitor"] = svc.get("lan") or href
    if desc:
        d["description"] = desc
    return {svc["name"]: d}


def main():
    inventory = yaml.safe_load((APP / "inventory.yaml").read_text())
    outside, lan = [], []
    layout = {CLUSTER_GROUP: {"tab": "Outside", "style": "row", "columns": 6}}
    for group in inventory:
        o = [tile(s, s["outside"], "LAN", s.get("lan")) for s in group["services"] if s.get("outside")]
        l = [tile(s, s["lan"], "outside", s.get("outside")) for s in group["services"] if s.get("lan")]
        if o:
            name = f"{group['group']} (outside)"
            outside.append({name: o})
            layout[name] = {"tab": "Outside", "style": "row", "columns": 6}
        if l:
            lan.append({group["group"]: l})
            layout[group["group"]] = {"tab": "LAN", "style": "row", "columns": 6}

    services = outside + lan
    (APP / "app/config/services.yaml").write_text(
        HEADER + yaml.safe_dump(services, sort_keys=False, allow_unicode=True, width=120))

    settings = {
        "title": "Homelab",
        "description": "Every web UI in the homelab",
        "theme": "dark",
        "color": "slate",
        "headerStyle": "boxed",
        "statusStyle": "dot",
        "hideVersion": True,
        "target": "_blank",
        "quicklaunch": {"searchDescriptions": True, "hideInternetSearch": True},
        "layout": layout,
    }
    (APP / "app/config/settings.yaml").write_text(
        HEADER + yaml.safe_dump(settings, sort_keys=False, allow_unicode=True, width=120))
    # Format like the pre-commit hook does, so a fresh run matches git exactly
    # (CI's "Homepage config" check relies on that).
    oxfmt = shutil.which("oxfmt")
    if not oxfmt:
        sys.exit("oxfmt not found: run inside the repo with mise (or npm i -g oxfmt)")
    subprocess.run([oxfmt, str(APP / "app/config/services.yaml"), str(APP / "app/config/settings.yaml")],
                   check=True, stdout=subprocess.DEVNULL)
    n_o = sum(len(next(iter(g.values()))) for g in outside)
    n_l = sum(len(next(iter(g.values()))) for g in lan)
    print(f"services.yaml: {n_o} outside + {n_l} LAN tiles in {len(services)} groups; settings.yaml: layout")


if __name__ == "__main__":
    main()
